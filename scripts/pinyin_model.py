def pair_weights():
    """
    返回 {(x, y): 权重}：x、y 是在输入同一个拼音时物理上前后相邻敲击的两个键。
    双向都记（音程与敲击方向无关），并补充"任意声母 × 任意韵母头字母"的低权重
    兜底，避免漏掉低频但合法的音节。
    """
    acc = defaultdict(int)
    for ini, fin, w in SYLLABLES:
        seq = ini + fin
        for x, y in zip(seq, seq[1:]):
            if x in INITIAL_LETTERS + FINAL_LETTERS and y in INITIAL_LETTERS + FINAL_LETTERS:
                acc[(x, y)] += w
                acc[(y, x)] += w
    for ini in INITIAL_LETTERS:
        if ini not in INITIAL_LETTERS:
            continue
        for head in "aoeiu":
            acc[(ini, head)] += 8
            acc[(head, ini)] += 8
        acc[(ini, "v")] += 3
        acc[("v", ini)] += 3
    for j in "jqx":            # ju qu xu 实际是 j/q/x + ü
        acc[(j, "v")] += 200
        acc[("v", j)] += 200
    for p in (("n", "g"), ("h", "i"), ("h", "a"), ("h", "o"), ("h", "u"), ("h", "e")):
        acc[p] = max(acc[p], 1500)   # -ng / zh ch sh 出现密度极高
    return dict(acc)


